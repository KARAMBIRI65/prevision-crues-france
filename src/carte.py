def fond_de_carte(ax=None, couleur="#e9e8e4", trait="#b9b7b0"):
    """Dessine la France métropolitaine et la Corse ; renvoie l'axe."""
    if ax is None:
        _, ax = plt.subplots(figsize=(7, 7))
    for poly in (FRANCE, CORSE):
        x, y = zip(*poly)
        ax.fill(x, y, color=couleur, zorder=0)
        ax.plot(x, y, color=trait, lw=0.8, zorder=1)
    ax.set_xlim(-5.3, 9.9)
    ax.set_ylim(41.2, 51.4)
    ax.set_aspect(1 / 0.68)   # corrige l'écrasement des longitudes vers 47° N
    ax.set_xticks([])
    ax.set_yticks([])
    for s in ax.spines.values():
        s.set_visible(False)
    return ax
